#include <bits/stdc++.h>
using namespace std;

static const int MOD = 998244353;
static const int ROOT = 3;

int modpow(int a, int e) {
    long long r = 1, x = a;
    while (e) {
        if (e & 1) r = r * x % MOD;
        x = x * x % MOD;
        e >>= 1;
    }
    return (int)r;
}

void ntt(vector<int>& a, bool invert) {
    int n = (int)a.size();
    for (int i = 1, j = 0; i < n; ++i) {
        int bit = n >> 1;
        for (; j & bit; bit >>= 1) j ^= bit;
        j ^= bit;
        if (i < j) swap(a[i], a[j]);
    }
    for (int len = 2; len <= n; len <<= 1) {
        int wlen = modpow(ROOT, (MOD - 1) / len);
        if (invert) wlen = modpow(wlen, MOD - 2);
        for (int i = 0; i < n; i += len) {
            long long w = 1;
            for (int j = 0; j < len / 2; ++j) {
                int u = a[i + j];
                int v = (int)(a[i + j + len / 2] * w % MOD);
                int x = u + v; if (x >= MOD) x -= MOD;
                int y = u - v; if (y < 0) y += MOD;
                a[i + j] = x;
                a[i + j + len / 2] = y;
                w = w * wlen % MOD;
            }
        }
    }
    if (invert) {
        int invn = modpow(n, MOD - 2);
        for (int& x : a) x = (long long)x * invn % MOD;
    }
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;
    while (t--) {
        int n;
        cin >> n;
        vector<int> a(n);
        int totalXor = 0;
        for (int& x : a) { cin >> x; totalXor ^= x; }

        vector<int> fact(n + 1), invfact(n + 1), cat(n + 1);
        fact[0] = 1;
        for (int i = 1; i <= n; ++i) fact[i] = (long long)fact[i - 1] * i % MOD;
        invfact[n] = modpow(fact[n], MOD - 2);
        for (int i = n; i; --i) invfact[i - 1] = (long long)invfact[i] * i % MOD;
        // Catalan numbers up to n-1 can be generated by recurrence.
        cat[0] = 1;
        for (int k = 0; k < n; ++k)
            cat[k + 1] = (long long)cat[k] * 2 * (2LL * k + 1) % MOD * modpow(k + 2, MOD - 2) % MOD;

        vector<int> weight(n + 1);
        for (int len = 1; len < n; ++len)
            weight[len] = (long long)cat[len - 1] * cat[n - len] % MOD;

        long long answer = 0;
        int m = 1;
        while (m < 2 * (n + 1) - 1) m <<= 1;
        for (int b = 0; b < 18; ++b) {
            vector<int> v(m);
            int pref = 0;
            v[0] = 1;
            for (int i = 1; i <= n; ++i) {
                pref ^= (a[i - 1] >> b) & 1;
                v[i] = pref ? MOD - 1 : 1;
            }
            ntt(v, false);
            vector<int> f = v;
            for (int k = 0; k < m; ++k)
                v[k] = (long long)f[k] * f[(m - k) & (m - 1)] % MOD;
            ntt(v, true);

            long long bitContribution = 0;
            long long bitValue = 1LL << b;
            for (int len = 1; len < n; ++len) {
                long long windows = n - len + 1;
                long long sameDiff = v[len];
                long long one = (windows % MOD - sameDiff + MOD) % MOD * ((MOD + 1) / 2) % MOD;
                long long term;
                if ((totalXor >> b) & 1) term = windows % MOD;
                else term = 2 * one % MOD;
                bitContribution = (bitContribution + term * weight[len]) % MOD;
            }
            answer = (answer + bitContribution * (bitValue % MOD)) % MOD;
        }
        cout << answer << '\n';
    }
    return 0;
}
